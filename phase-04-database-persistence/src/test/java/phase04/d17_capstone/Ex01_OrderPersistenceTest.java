    /** Real JDBC delegate: counts executions, gates connection acquisition, injects post-write failures only. */
    static class JdbcProbe implements DataSource {
        final DataSource delegate;
        final AtomicInteger connections = new AtomicInteger(), executions = new AtomicInteger(), inserts = new AtomicInteger();
        final List<String> sql = Collections.synchronizedList(new ArrayList<>());
        final List<Map<Integer, Object>> bindings = Collections.synchronizedList(new ArrayList<>());
        final List<List<Binding>> bindingCalls = Collections.synchronizedList(new ArrayList<>());
        record Binding(Method method, Object[] arguments) {
            void replay(PreparedStatement statement) throws SQLException {
                try { method.invoke(statement, arguments); }
                catch (InvocationTargetException failure) {
                    if (failure.getCause() instanceof SQLException sql) throw sql;
                    throw new SQLException("Captured binding failed", failure.getCause());
                } catch (ReflectiveOperationException failure) { throw new SQLException("Cannot replay captured binding", failure); }
            }
        }
        final List<Integer> backendPids = Collections.synchronizedList(new ArrayList<>());
        CountDownLatch ready, go;
        Throwable fault;
        boolean failRollback;
        JdbcProbe(DataSource delegate) { this.delegate = delegate; }
        @Override public Connection getConnection() throws SQLException { return wrap(delegate.getConnection()); }
        @Override public Connection getConnection(String user, String password) throws SQLException { return wrap(delegate.getConnection(user, password)); }
        Connection wrap(Connection connection) throws SQLException {
            connections.incrementAndGet();
            try {
                if (ready != null) {
                    try (var s = connection.createStatement()) {
                        s.setQueryTimeout(10);
                        try (var r = s.executeQuery("SELECT pg_backend_pid()")) { r.next(); backendPids.add(r.getInt(1)); }
                    }
                    ready.countDown();
                    if (!go.await(10, TimeUnit.SECONDS)) throw new SQLException("Connection gate timed out");
                }
            } catch (InterruptedException interrupted) {
                Thread.currentThread().interrupt(); connection.close(); throw new SQLException("Connection gate interrupted", interrupted);
            } catch (SQLException failure) { connection.close(); throw failure; }
            return (Connection) Proxy.newProxyInstance(Connection.class.getClassLoader(), new Class<?>[]{Connection.class}, (proxy, method, args) -> {
                Object value;
                try { value = method.invoke(connection, args); }
                catch (InvocationTargetException failure) { throw failure.getCause(); }
                if (method.getName().equals("rollback") && failRollback) throw new SQLException("rollback probe after real rollback");
                if (value instanceof Statement statement) {
                    String preparedSql = args != null && args.length > 0 && args[0] instanceof String query ? query : null;
                    Class<?> type = statement instanceof CallableStatement ? CallableStatement.class
                            : statement instanceof PreparedStatement ? PreparedStatement.class : Statement.class;
                    var params = new TreeMap<Integer, Object>();
                    var calls = new ArrayList<Binding>();
                    return Proxy.newProxyInstance(type.getClassLoader(), new Class<?>[]{type}, (p, m, a) -> {
                        if (m.getName().equals("clearParameters")) { params.clear(); calls.clear(); }
                        if (m.getName().startsWith("set") && a != null && a.length >= 2 && a[0] instanceof Integer index) {
                            params.put(index, a[1]); calls.add(new Binding(m, a.clone()));
                        }
                        if (m.getName().startsWith("execute")) {
                            String query = a != null && a.length > 0 && a[0] instanceof String text ? text : preparedSql;
                            executions.incrementAndGet(); sql.add(query); bindings.add(new TreeMap<>(params));
                            bindingCalls.add(List.copyOf(calls));
                            if (fault != null && query != null && query.startsWith("INSERT INTO order_items")
                                    && inserts.incrementAndGet() == 2) throw fault;
                        }
                        try { return m.invoke(statement, a); }
                        catch (InvocationTargetException failure) { throw failure.getCause(); }
                    });
                }
                return value;
            });
        }
        @Override public PrintWriter getLogWriter() throws SQLException { return delegate.getLogWriter(); }
        @Override public void setLogWriter(PrintWriter writer) throws SQLException { delegate.setLogWriter(writer); }
        @Override public int getLoginTimeout() throws SQLException { return delegate.getLoginTimeout(); }
        @Override public void setLoginTimeout(int seconds) throws SQLException { delegate.setLoginTimeout(seconds); }
        @Override public Logger getParentLogger() { return Logger.getLogger("task6-jdbc-probe"); }
        @Override public <T> T unwrap(Class<T> type) throws SQLException { return delegate.unwrap(type); }
        @Override public boolean isWrapperFor(Class<?> type) throws SQLException { return delegate.isWrapperFor(type); }
    }
