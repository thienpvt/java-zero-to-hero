    String explain(String sql, List<JdbcProbe.Binding> capturedBindings) throws SQLException {
        try (var c = ds.getConnection(); var s = c.prepareStatement("EXPLAIN (ANALYZE, BUFFERS, FORMAT TEXT) " + sql)) {
            s.setQueryTimeout(10);
            for (var binding : capturedBindings) binding.replay(s);
            try (var rows = s.executeQuery()) {
                StringBuilder plan = new StringBuilder();
                while (rows.next()) plan.append(rows.getString(1)).append('\n');
                return plan.toString();
            }
        }
    }
