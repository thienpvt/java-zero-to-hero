    @Test @DisplayName("Q3 — Hai request/backend độc lập không oversell, lượng bán cộng tồn bằng ban đầu")
    void q03_twoIndependentRequestsConserveStock() throws Exception {
        assertTrue(Ex01_OrderPersistence.createOrder(ds, 2, List.of(new Line(1, 1))) > 0);
        execute("UPDATE products SET stock=1 WHERE id=1");
        JdbcProbe probe = new JdbcProbe(ds);
        probe.ready = new CountDownLatch(2); probe.go = new CountDownLatch(1);
        var pool = Executors.newFixedThreadPool(2);
        boolean terminated;
        try {
            var first = pool.submit(() -> buyLast(probe));
            var second = pool.submit(() -> buyLast(probe));
            assertTrue(probe.ready.await(10, TimeUnit.SECONDS));
            probe.go.countDown();
            int accepted = first.get(25, TimeUnit.SECONDS) + second.get(25, TimeUnit.SECONDS);
            assertEquals(1, accepted); assertEquals(2, new HashSet<>(probe.backendPids).size());
            assertEquals(1, accepted + stock(1));
            assertEquals(1, scalar("SELECT sum(i.quantity) FROM order_items i JOIN orders o ON o.id=i.order_id WHERE o.customer_id=1"));
            assertEquals(1, scalar("SELECT count(*) FROM orders WHERE customer_id=1"));
            System.out.println("B17 independentBackends=2 initialStock=1 accepted=1 finalStock=0");
        } finally {
            probe.go.countDown(); pool.shutdownNow();
            try { terminated = pool.awaitTermination(10, TimeUnit.SECONDS); }
            catch (InterruptedException interrupted) { Thread.currentThread().interrupt(); terminated = false; }
        }
        assertTrue(terminated); // reached only when no primary failure needs preserving
    }

